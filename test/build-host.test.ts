// build-host 防回归：产物 host.js 里的跨包依赖必须是「外部化裸说明符」，而不是被内联。
//
// 为什么值得一条测试（两个坏方向都不报错、只在线上发作）：发布形态下 host.js 躺在
// node_modules 里被 dsh 载入——
//   1) 内联：`@jayyuen66/dsh-plugin-shared/lib/*` 一旦被打进产物，shared 的模块级状态就在每个插件
//      里各复制一份；rolldown 的 external 字符串项是精确匹配，只列包名会漏掉**子路径**，
//      故 build-host.mjs 按「包名段」判定（该坑已在脚本注释登记）。
//   2) 残留：产物里只要还剩 `./lib/xxx.ts`，Node 载入即抛 ERR_UNSUPPORTED_NODE_MODULES_
//      TYPE_STRIPPING；而 dependencies 里跑掉一个包（如 schemastery 退回 devDependencies）
//      就会被整包内联——体积翻倍正是内联发生了的指纹，故一并钉住。
import { describe, it } from "vitest";
import assert from "node:assert/strict";
import { buildHost, singleEntryChunk } from "../build-host.mjs";
import { hostFreshnessEvidence } from "./host-freshness.ts";

/** 一次构建结果供本文件的产物断言复用：rolldown 每跑一次都是完整打包，逐用例重跑只会拖长套件。 */
let builtHost: Promise<string> | undefined;
async function hostCode(): Promise<string> {
  builtHost ??= buildHost();
  return builtHost;
}

/** 产物里 external 说明符的语句级判据：子串匹配会把内联模块里的同类文本当成命中。 */
function externalSpecifier(specifier: string): RegExp {
  return new RegExp(String.raw`\bfrom\s+["']${specifier}["']\s*;`, "u");
}

describe("buildHost()", () => {
  it("host.js 与最新构建逐字节一致（改 host.ts / lib/*.ts 后必须 node build-host.mjs）", async () => {
    const { pkgName, pkgDir, onDisk, built } = await hostFreshnessEvidence(import.meta.url);
    assert.equal(
      onDisk,
      built,
      `[${pkgName}] host.js 已过期：host.ts（或其依赖）变更后未重建。请运行：cd ${pkgDir} && node build-host.mjs`,
    );
  });

  it("产物 host.js：运行期跨包依赖保持 external（未内联）", async () => {
    const out = await hostCode();
    assert.ok(
      out.startsWith("// GENERATED by build-host.mjs"),
      "产物须带生成标记（勿手改 host.js）",
    );
    // 值导入的包必须列在 dependencies，否则被内联。判据按语句形态而不是子串：
    // 内联模块里的错误消息或注释同样可能包含 `from "..."`，子串匹配会给出假绿。
    assert.match(
      out,
      externalSpecifier("@deepseek-ai/schemastery"),
      "宿主 fork 的 schemastery 必须外部化（0.1.7 的 volatile 字段解析只有它有实现）",
    );
    // 反向锁：不得退回公共 schemastery——它没有 .volatile()，volatile 字段解析出的仍是
    // 普通值，设置卡写进去的值永远读不到（0.1.7 迁移的根因）。三种引入形态与子路径都算：
    // 只认 `from 'schemastery'` 时，`import "schemastery"` / `require(...)` / 子路径全会漏过。
    assert.doesNotMatch(
      out,
      /(?:\bfrom\s+|\bimport\s*\(?\s*|\brequire\s*\(\s*)["']schemastery(?:\/[^"']*)?["']/u,
      "产物不得再值导入公共 schemastery（volatile 解析只在宿主 fork 里）",
    );
    // 子路径说明符：external 字符串项匹配不到的那个坑
    assert.match(
      out,
      externalSpecifier("@jayyuen66/dsh-plugin-shared/lib/tool-events"),
      "shared/tool-events 必须外部化",
    );
    assert.match(
      out,
      externalSpecifier("@jayyuen66/dsh-plugin-shared/lib/project-key"),
      "shared/project-key 必须外部化（lib/gateway-target.ts 的 project 单源，内联会让网关反馈与 lesson 总线各算一份键）",
    );
    assert.match(
      out,
      externalSpecifier("@jayyuen66/dsh-plugin-shared/lib/locale"),
      "shared/locale 必须外部化（host 侧文案语言与官方 locale 偏好同源，内联会把 resolveLocale 复制进每个插件）",
    );
    assert.match(
      out,
      externalSpecifier("@deepseek-ai/dsh-credentials"),
      "dsh-credentials 必须外部化（口径 A：值导入落 dependencies）",
    );
    // 内联检测覆盖声明式与赋值式两种形态：只认行首无缩进的 `function name(` 时，
    // 打包器改写成 `const credentialRef = (...) => ...` 这份守卫会静默失效。
    assert.doesNotMatch(
      out,
      /(?:function\s+|(?:const|let|var)\s+)(?:credentialRef|isCredentialRefName|brandString|brandNumber)\s*[(=]/u,
      "产物不得内联官方 branded-string 构造器（出现函数体=依赖又落回 devDependencies）",
    );
    assert.match(
      out,
      externalSpecifier("@jayyuen66/dsh-plugin-shared/lib/record"),
      "shared/record 必须外部化（SP-D 起 isRecord/fieldOf 单点在 shared；本包那份异形 messageOf 仍留本地）",
    );
  });

  it("产物 host.js：不残留相对路径的 TS 说明符", async () => {
    const out = await hostCode();
    // lib/*.ts 应已被吃进单文件；留着即"发布后 Node 直接拒载"的形态。`../`、 tsx/mts/cts
    // 与模板引号都要算：只认 `"./x.ts"` 时，`import(\`./${name}.ts\`)` 这类形态会整片漏过。
    assert.doesNotMatch(
      out,
      /["'`]\.{1,2}\/[^"'`\n]*\.(?:ts|tsx|mts|cts)["'`]/u,
      "不得有 ./x.ts / ../x.ts 形态的相对说明符残留",
    );
  });
});

/** 输出守卫测试用的最小 chunk 正文。 */
const CHUNK_CODE = "export {};";
/** 输出守卫测试用的产物文件名。 */
const ARTIFACT_FILE = "artifact.js";

/**
 * 造一个最小输出项；判据只看 type/fileName/isEntry/code。
 * @param type - rolldown 输出项类型
 * @param fileName - 产物文件名
 * @param extra - 该类型需要的其余字段
 * @returns 可交给 singleEntryChunk 的输出项
 */
type OutputItem =
  | {
      type: "chunk";
      fileName: string;
      code: string;
      isEntry?: boolean;
      moduleIds?: readonly string[];
    }
  | { type: "asset"; fileName: string };

function outputItem(
  type: "chunk" | "asset",
  fileName: string,
  extra: Partial<{ isEntry: boolean; code: string }> = {},
): OutputItem {
  if (type === "asset") {
    return { type, fileName };
  }
  return {
    type,
    fileName,
    code: extra.code ?? "",
    ...(extra.isEntry === undefined ? {} : { isEntry: extra.isEntry }),
  };
}

describe("单文件产物的输出守卫", () => {
  it("拒绝多个 chunk：单文件产物不能静默丢掉第二个", () => {
    const output = [
      outputItem("chunk", ARTIFACT_FILE, { isEntry: true, code: CHUNK_CODE }),
      outputItem("chunk", "chunk-abc.js", { isEntry: false, code: CHUNK_CODE }),
    ];
    assert.throws(() => singleEntryChunk(output, "entry.ts"), /2 项输出/u);
  });

  it("拒绝唯一的 asset：asset 没有正文，不满足 entry chunk 判据", () => {
    // 上一例（chunk + asset）走的是数量守卫；这一例只有一个 asset，数量恰为 1，
    // 因此真正被评估的是「是不是带正文的 entry chunk」这一支，asset 语义由此单独覆盖。
    const output = [outputItem("asset", "x.css")];
    assert.throws(() => singleEntryChunk(output, "entry.ts"), /entry chunk/u);
  });

  it("拒绝非 entry 的单个 chunk", () => {
    const output = [outputItem("chunk", "chunk-abc.js", { isEntry: false, code: CHUNK_CODE })];
    assert.throws(() => singleEntryChunk(output, "entry.ts"), /entry chunk/u);
  });

  it("拒绝空正文的 entry chunk：空产物落盘后宿主加载得到的是一个不生效的插件", () => {
    const output = [outputItem("chunk", ARTIFACT_FILE, { isEntry: true, code: "  \n " })];
    assert.throws(() => singleEntryChunk(output, "entry.ts"), /entry chunk/u);
  });

  it("接受唯一的 entry chunk", () => {
    const output = [outputItem("chunk", ARTIFACT_FILE, { isEntry: true, code: CHUNK_CODE })];
    const chunk = singleEntryChunk(output, "entry.ts");
    assert.equal(chunk.code, CHUNK_CODE);
  });
});
