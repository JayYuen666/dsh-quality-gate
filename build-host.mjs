#!/usr/bin/env node
// @ts-check
/// <reference types="node" />
// 构建 host.js：rolldown 把 host.ts 及其 `./lib/*` 依赖打成单文件 ESM，落在**包根**
// （与源码同目录，故 `import.meta.dirname` 的语义与源码态完全一致）。
// 编排（输出守卫、region 正典化、moduleIds 结构性判据）统一住在
// @jayyuen66/dsh-plugin-shared/lib/build-host，一处可改；本文件只声明本仓的入口、产物、
// 生成头，与一项仓有取舍：optionalDependencies 刻意不外部化——可选依赖的语义是「可能
// 没装」，外部化会在产物里留一条解析不了的裸说明符，宿主载入时是整个插件
// MODULE_NOT_FOUND；打包进产物则是「缺包时功能照旧」。（与兄弟仓「外部化、由运行期
// require 决定」的取向相反，两边各有实据，故做成显式开关而不是统一值。）
// 不产 .d.ts：插件包对外没有 TS API——dsh 按包名载入运行，没有人 import 它。
import path from "node:path";
import { rolldown } from "rolldown";
import { buildHostEntries } from "@jayyuen66/dsh-plugin-shared/lib/build-host";
import { invokedDirectly, writeArtifact } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

export { singleEntryChunk } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

const root = import.meta.dirname;

/** 生成 host.js 的完整文本。 */
export async function buildHost() {
  const artifacts = await buildHostEntries({
    root,
    rolldown,
    externalizeOptional: false,
    entries: [
      {
        source: "host.ts",
        output: "host.js",
        header:
          "// GENERATED by build-host.mjs — edit host.ts / lib/*.ts, then run `node build-host.mjs`.\n",
      },
    ],
  });
  const artifact = artifacts.find((item) => item.output === "host.js");
  if (artifact === undefined) {
    throw new Error("buildHostEntries 交回的产物清单里没有 host.js");
  }
  return artifact.code;
}

async function main() {
  const out = await buildHost();
  await writeArtifact(path.join(root, "host.js"), out);
  console.info("host.js written:", Buffer.byteLength(out, "utf8"), "bytes");
}

if (invokedDirectly(import.meta.filename)) {
  try {
    await main();
  } catch (error) {
    console.error(error);
    process.exitCode = 1;
  }
}
